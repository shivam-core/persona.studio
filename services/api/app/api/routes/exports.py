"""Export endpoints generating CSV, JSON, and printable HTML documents."""

import io
from fastapi import APIRouter, Depends, HTTPException, Response
from fastapi.responses import HTMLResponse
from sqlalchemy import select
from sqlalchemy.orm import Session
import pandas as pd

from app.db.session import get_db
from app.db.models.persona import PersonaCard, EvidenceMetric
from app.db.models.campaign import Campaign
from app.db.models.simulation import SimulationRun
from app.db.models.experiment import Experiment, ExperimentAnalysis as DBExperimentAnalysis

router = APIRouter(prefix="/exports", tags=["Exports"])


@router.get("/persona/{card_id}/html", response_class=HTMLResponse)
def export_persona_printable_html(card_id: str, db: Session = Depends(get_db)):
    """Generate printable HTML report for a persona card."""
    card = db.execute(select(PersonaCard).where(PersonaCard.id == card_id)).scalars().first()
    if not card:
        raise HTTPException(status_code=404, detail="Persona card not found.")

    metrics = db.execute(
        select(EvidenceMetric).where(EvidenceMetric.persona_card_id == card_id)
    ).scalars().all()

    metric_rows = "".join(
        f"<tr><td>{em.display_label}</td><td><strong>{em.value} {em.unit}</strong></td><td>{em.baseline_value}</td><td>{em.aggregation}</td></tr>"
        for em in metrics
    )

    hypo_items = "".join(
        f"<li>{h.get('text', '')}</li>" for h in card.hypotheses_json or []
    )

    html = f"""<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  <title>{card.display_name} — Persona Studio Brief</title>
  <style>
    body {{ font-family: -apple-system, sans-serif; margin: 40px; color: #17233B; background: #fff; }}
    h1 {{ font-size: 24px; color: #5146D9; margin-bottom: 4px; }}
    .badge {{ display: inline-block; padding: 4px 8px; border-radius: 4px; background: #EEF2F6; font-size: 12px; font-weight: 600; }}
    .summary {{ font-size: 15px; margin: 16px 0; line-height: 1.5; color: #52617A; }}
    table {{ width: 100%; border-collapse: collapse; margin-top: 20px; }}
    th, td {{ text-align: left; padding: 10px; border-bottom: 1px solid #E2E8F2; font-size: 13px; }}
    th {{ background: #F5F7FB; color: #17233B; }}
    .footer {{ margin-top: 40px; font-size: 11px; color: #94A3B8; border-top: 1px solid #E2E8F2; padding-top: 10px; }}
  </style>
</head>
<body>
  <div style="display: flex; justify-content: space-between; align-items: center;">
    <h1>{card.display_name}</h1>
    <span class="badge" style="background: {card.color_hex}; color: #fff;">Audience: {card.audience_count} ({card.audience_share*100:.1f}%)</span>
  </div>
  <p class="summary">{card.summary_text}</p>
  <h3>Grounded Evidence Metrics</h3>
  <table>
    <thead><tr><th>Metric</th><th>Segment Value</th><th>Population Baseline</th><th>Aggregation</th></tr></thead>
    <tbody>{metric_rows}</tbody>
  </table>
  <h3 style="margin-top: 30px;">Test Hypotheses</h3>
  <ul>{hypo_items}</ul>
  <div class="footer">Generated by Persona Studio — Synthetic Demo. Document is versioned and grounded in empirical data.</div>
</body>
</html>"""
    return HTMLResponse(content=html)


